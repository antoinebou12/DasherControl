use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct CaddySiteInput {
    pub hostname: String,
    /// Upstream like `127.0.0.1:8080` or `mycontainer:80`.
    pub upstream: String,
    #[serde(default)]
    pub tls_email: Option<String>,
    #[serde(default)]
    pub path_prefix: Option<String>,
    #[serde(default)]
    pub encode: bool,
}

#[derive(Debug, Deserialize)]
pub struct CaddyGenerateBody {
    pub sites: Vec<CaddySiteInput>,
}

fn contains_injection(s: &str) -> bool {
    s.chars().any(|c| c == '\n' || c == '\r' || c == '`')
}

pub fn validate_sites(sites: &[CaddySiteInput]) -> Result<(), &'static str> {
    for s in sites {
        if s.hostname.is_empty() || s.upstream.is_empty() {
            return Err("hostname and upstream are required");
        }
        if contains_injection(&s.hostname)
            || contains_injection(&s.upstream)
            || s.path_prefix.as_ref().map_or(false, |p| contains_injection(p))
            || s.tls_email.as_ref().map_or(false, |e| contains_injection(e))
        {
            return Err("invalid characters in input");
        }
    }
    Ok(())
}

/// Build a Caddy v2 Caddyfile (one server block per site).
pub fn generate_caddyfile(sites: &[CaddySiteInput]) -> String {
    let mut out = String::from("# Generated by DasherControl — review before use.\n\n");
    for site in sites {
        out.push_str(&site_block(site));
        out.push('\n');
    }
    out
}

fn site_block(s: &CaddySiteInput) -> String {
    let mut block = format!("{} {{\n", s.hostname);
    if let Some(ref email) = s.tls_email {
        let e = email.trim();
        if !e.is_empty() {
            block.push_str(&format!("\ttls {}\n", e));
        }
    }
    if s.encode {
        block.push_str("\tencode zstd gzip\n");
    }
    let upstream = s.upstream.trim();
    if let Some(ref prefix) = s.path_prefix {
        let p = prefix.trim().trim_matches('/').to_string();
        if !p.is_empty() {
            block.push_str(&format!("\thandle_path /{p}/* {{\n"));
            block.push_str(&format!("\t\treverse_proxy {upstream}\n"));
            block.push_str("\t}\n");
        } else {
            block.push_str(&format!("\treverse_proxy {upstream}\n"));
        }
    } else {
        block.push_str(&format!("\treverse_proxy {upstream}\n"));
    }
    block.push_str("}\n");
    block
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_reverse_proxy() {
        let sites = vec![CaddySiteInput {
            hostname: "app.example.com".into(),
            upstream: "127.0.0.1:3000".into(),
            tls_email: None,
            path_prefix: None,
            encode: false,
        }];
        let f = generate_caddyfile(&sites);
        assert!(f.contains("app.example.com"));
        assert!(f.contains("reverse_proxy 127.0.0.1:3000"));
    }

    #[test]
    fn validate_sites_rejects_empty_hostname() {
        let sites = vec![CaddySiteInput {
            hostname: "".into(),
            upstream: "127.0.0.1:1".into(),
            tls_email: None,
            path_prefix: None,
            encode: false,
        }];
        assert_eq!(validate_sites(&sites), Err("hostname and upstream are required"));
    }

    #[test]
    fn validate_sites_rejects_injection_in_hostname() {
        let sites = vec![CaddySiteInput {
            hostname: "evil\ninject".into(),
            upstream: "127.0.0.1:1".into(),
            tls_email: None,
            path_prefix: None,
            encode: false,
        }];
        assert_eq!(validate_sites(&sites), Err("invalid characters in input"));
    }

    #[test]
    fn validate_sites_rejects_injection_in_path_prefix() {
        let sites = vec![CaddySiteInput {
            hostname: "ok.example".into(),
            upstream: "127.0.0.1:1".into(),
            tls_email: None,
            path_prefix: Some("api`x".into()),
            encode: false,
        }];
        assert_eq!(validate_sites(&sites), Err("invalid characters in input"));
    }

    #[test]
    fn generate_caddyfile_includes_encode_and_handle_path() {
        let sites = vec![CaddySiteInput {
            hostname: "api.example.com".into(),
            upstream: "10.0.0.5:8080".into(),
            tls_email: Some("ops@example.com".into()),
            path_prefix: Some("/v1".into()),
            encode: true,
        }];
        let f = generate_caddyfile(&sites);
        assert!(f.contains("encode zstd gzip"));
        assert!(f.contains("handle_path /v1/*"));
        assert!(f.contains("reverse_proxy 10.0.0.5:8080"));
        assert!(f.contains("\ttls ops@example.com\n"));
    }
}
